export const LANGUAGES = {
  en: { label: "English", dict: {} as Dict },
  es: { label: "Español", dict: es },
  pt: { label: "Português", dict: pt },
  fr: { label: "Français", dict: fr },
  de: { label: "Deutsch", dict: de },
  it: { label: "Italiano", dict: it },
  zh: { label: "简体中文", dict: zh },
} as const;

export type Lang = keyof typeof LANGUAGES;

export function detectLang(): Lang {
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.slice(0, 2).toLowerCase();
    if (code in LANGUAGES) return code as Lang;
  }
  return "en";
}

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = LANGUAGES[lang]?.dict[key] ?? en[key];
  const all: Record<string, string | number> = {
    trash: LANGUAGES[lang]?.dict[isWindows ? "recycleBin" : "trash"] ?? en[isWindows ? "recycleBin" : "trash"],
    ...vars,
  };
  if (s.includes("{")) {
    s = s.replace(/\{(\w+)\}/g, (m, name) => (name in all ? String(all[name]) : m));
  }
  return s;
}

export function useT() {
  const { settings } = useSettings();
  return useCallback(
    (key: Key, vars?: Record<string, string | number>) => translate(settings.lang, key, vars),
    [settings.lang],
  );
}
